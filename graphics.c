//*******************************************************
//*	Initialize the graphics								*
//*	You must run this prior to doing graphics stuff.	*
//*******************************************************
int		initGraphics(void)
{
	system("tput civis"); // Hide the cursor!
	
	// Open the file for reading and writing
    fbfd = open("/dev/fb0", O_RDWR);
    if (!fbfd)
    {
      printf("Error: cannot open framebuffer device.\n");
      return(1);
    }

    // Get variable screen information
    if (ioctl(fbfd, FBIOGET_VSCREENINFO, &vinfo))
    {
		printf("Error reading variable information.\n");
		return(1);
    }

    // Store for reset (copy vinfo to vinfo_orig)
    memcpy(&orig_vinfo, &vinfo, sizeof(struct fb_var_screeninfo));

    // Change variable info
    vinfo.bits_per_pixel = 8;
    if (ioctl(fbfd, FBIOPUT_VSCREENINFO, &vinfo))
    {
		printf("Error setting variable information.\n");
		return(1);
    }

    // Get fixed screen information
    if (ioctl(fbfd, FBIOGET_FSCREENINFO, &finfo))
    {
		printf("Error reading fixed information.\n");
		return(1);
    }

    // map fb to user mem 
    screenSize = vinfo.xres * vinfo.yres;
    fbp = (char*)mmap(0, 
              screenSize, 
              PROT_READ | PROT_WRITE, 
              MAP_SHARED, 
              fbfd, 
              0);

    if ((int)fbp == -1)
    {
        printf("Failed to mmap.\n");
		return(1);
    }
    else
    {
		// Clear screen to black
		memset(fbp, 0, screenSize);
	}
	graphics_have_been_initialized = 1;
//	printf("Alleged x resolution: %d\n", vinfo.xres);
//	printf("Alleged y resolution: %d\n", vinfo.yres);
	return(0);
}

//*******************************************
//*	Restore the graphics					*
//*	Put stuff back the way is wuz.			*
//*******************************************
int		restoreGraphics(void)
{
	// Clean up your mess!
	munmap(fbp, screenSize);
	if(ioctl(fbfd, FBIOPUT_VSCREENINFO, &orig_vinfo))
	{
		printf("Error resetting variable information.\n");
		return(1);
	}
	
	// Close file
	close(fbfd);
	system("tput cnorm");	// Show the cursor!
	graphics_have_been_initialized = 0;
	return 0;
}

//	Draw a pixel in a specified color from the palette.
int		putPixel(int x, int y, int color)
{
	// Validate this stuff!
	if(!graphics_have_been_initialized)
	{
		printf("Graphics have not been initialized.\n");
		exit(1);
	}
	
	if(x > vinfo.xres - 1 || x < 0)
	{
		if(!SUPPRESS_ERROR_MESS)
		{
			printf("putPixel Error - Invalid x: %d\n", x);
		}
		return(1);
	}

	if(y > MAX_Y || y < 0)
	{
		if(!SUPPRESS_ERROR_MESS)
		{
			printf("putPixel Error - Invalid y: %d\n", y);
		}
		return(1);
	}

	// Transpose y?
	if(TRANSPOSE_Y)
	{
		y = MAX_Y - y;
	}

    // Calculate the pixel's byte offset inside the buffer
    unsigned int pix_offset = x + y * finfo.line_length; 
	if(color == COLOR_CLEAR)
	{
		color = getPixel(x, y);
	}
	
    // Now this is about the same as 'fbp[pix_offset] = value'
    *((char*)(fbp + pix_offset)) = color;
	return(0);
}

//	Read a pixel's current color in the current palette.
int		getPixel(int x, int y)
{
    // Calculate the pixel's byte offset inside the buffer
    unsigned int pix_offset = x + y * finfo.line_length;

    // Now this is about the same as 'color = fbp[pix_offset]'
    return(*((char*)(fbp + pix_offset)));
}

// Draw a line in the specified color.
// If the first point (x0, y0) is (-1, -1),
//	the line is drawn from the previously drawn line's
//	(x1, y1) point.
int	drawLine(int x0, int y0, int x1, int y1, int color)
{
	int	intAbsDiff(int number1, int number2);

	int steep;
	int dx, dy;
	int err;
	int ystep;
	int	temp;
	
	// If first coordinate pair is (-1, -1),
	// continue from last drawn line's endpoint.
	static	int	lastX = -1;	// Save last values for continuation
	static	int	lastY = -1;	// from last line drawn.

	if(x0 == -1 && y0 == -1)
	{
		if(lastX == -1 && lastY == -1)
		{
			// What were ya thinkin'?
			printf("There is no previous line.\n");
			return(1);
		}
		x0 = lastX;
		y0 = lastY;
	}
	lastX = x1;
	lastY = y1;

	temp = intAbsDiff(y1, y0);
	temp = intAbsDiff(x1, x0);
	
	steep = intAbsDiff(y1, y0) > intAbsDiff(x1, x0);
	if (steep)
	{
		//swap(x0, y0);
		temp = x0;
		x0 = y0;
		y0 = temp;
		
		//swap(x1, y1);
		temp = x1;
		x1 = y1;
		y1 = temp;
		
	}

	if (x0 > x1)
	{
		//swap(x0, x1);
		temp = x0;
		x0 = x1;
		x1 = temp;
		
		//swap(y0, y1);
		temp = y0;
		y0 = y1;
		y1 = temp;
		
	}

	dx = x1 - x0;
	dy = intAbsDiff(y1, y0);
	err = dx / 2;

	if (y0 < y1)
	{
		ystep = 1;
	}
	else
	{
		ystep = -1;
	}

	for (; x0<=x1; x0++)
	{
		if (steep)
		{
			if(putPixel(y0, x0, color))
			{
				return(1);
			}
		}
		else
		{
			if(putPixel(x0, y0, color))
			{
				return(1);
			}
		}
		err -= dy;
		if (err < 0)
		{
			y0 += ystep;
			err += dx;
		}
	}
//printf("(%d, %d) - (%d, %d)     color = %d\n", x0, y0, x1, y1, color); 	
	return(0);
}

// Determine the absolute value of the differential of two integers.
//	Used by drawLine function.
int			intAbsDiff(int number1, int number2)
{
	if(number1 > number2)
	{
		return(number1 - number2);
	}
	return(number2 - number1);
}

// Draw a circle in the specified color.
int	drawCircle(int x0, int y0, int r, int color)
{
	int f;
	int ddF_x;
	int ddF_y;
	int x;
	int y;

	f = 1 - r;
	ddF_x = 1;
	ddF_y = -2 * r;
	x = 0;
	y = r;

	if(putPixel(x0, y0, color))
	{
		return(1);
	}
	if(putPixel(x0, (y0+r), color))
	{
		return(1);
	}
	if(putPixel(x0, (y0-r), color))
	{
		return(1);
	}
	if(putPixel((x0+r), y0, color))
	{
		return(1);
	}
	if(putPixel((x0-r), y0, color))
	{
		return(1);
	}

	while (x<y)
	{
		if (f >= 0)
		{
			y--;
			ddF_y += 2;
			f += ddF_y; 
		}
		x++;
		ddF_x += 2;
		f += ddF_x;
  
		if(putPixel((x0 + x), (y0 + y), color))
		{
			return(1);
		}
		if(putPixel((x0 - x), (y0 + y), color))
		{
			return(1);
		}
		if(putPixel((x0 + x), (y0 - y), color))
		{
			return(1);
		}
		if(putPixel((x0 - x), (y0 - y), color))
		{
			return(1);
		}
		if(putPixel((x0 + y), (y0 + x), color))
		{
			return(1);
		}
		if(putPixel((x0 - y), (y0 + x), color))
		{
			return(1);
		}
		if(putPixel((x0 + y), (y0 - x), color))
		{
			return(1);
		}
		if(putPixel((x0 - y), (y0 - x), color))
		{
			return(1);
		}
	}
	return(0);
}
// Draw a rectamgle in the specified color.
int		drawRect(int x0, int y0, int x1, int y1, int color, int fill)
{
	int	temp;
	if(fill == 0)	// Just draw a box
	{
		drawLine(x0, y0, x1, y0, color);
		drawLine(x1, y0, x1, y1, color);
		drawLine(x1, y1, x0, y1, color);
		drawLine(x0, y1, x0, y0, color);
	}
	else	// Draw a filled box
	{
		if(y1 < y0)
		{
			temp = y1;
			y1 = y0;
			y0 = temp;
		}
		for(;y0 <= y1; y0++)
		{
			drawLine(x0, y0, x1, y0, color);
		}
	}
	return(0);
}

