//	Draw a character in the tiny 5x7 font.
int		drawChar(char charIn, int xpos, int ypos, int colorFG, int colorBG)
{
	int columnCtr, bitCtr;
	const unsigned char	*FontDataPtr;

	FontDataPtr = &CHARMAP[((int)charIn - 32) * 5];
	for(columnCtr = 0; columnCtr <= 4; columnCtr++)
	{
		for(bitCtr = 7; bitCtr > 0; bitCtr--)
		{
			if(*FontDataPtr & 0b00000001 << (bitCtr - 1))
			{
				putPixel(xpos + columnCtr, ypos - bitCtr, colorFG);
			}
			else if(colorBG >= 0) // Set to BG color if not transparent 
			{
				putPixel(xpos + columnCtr, ypos - bitCtr, colorBG);
			}
		}
		FontDataPtr++;	// Point to next column in char
	}

	return(0);
}
	
//	Draw a string of characters in the tiny 5x7 font.
int		drawString(char *theString, int xpos, int ypos, int colorFG, int colorBG)
{
	int	xOff = 0;
	while(*theString != '\0')
	{
		drawChar(*theString++, xpos + xOff++ * 7, ypos, colorFG, colorBG);
	}
	return(0);
}
//	Draw a character in the Hershey Vector Font.
int		drawVectorChar(char charIn, int xpos, int ypos, int colorFG)
{
	int	fontIndex, pairCount, horizSpace, x0, y0, x1, y1, fontColor;
	
	fontIndex = 0;
	// Get the number of vertex coordinate pairs for font character
	pairCount = simplex[charIn - 32][fontIndex++];
	
	// Get standard spacing value for font character
	horizSpace = simplex[charIn - 32][fontIndex++];
	
	// Get the first vertex coordinate pair for font character
	x0 = simplex[charIn - 32][fontIndex++];
	y0 = simplex[charIn - 32][fontIndex++];
	fontColor = colorFG;
	while(fontIndex <= pairCount * 2)
	{
		x1 = simplex[charIn - 32][fontIndex++];
		y1 = simplex[charIn - 32][fontIndex++];
		
		if(x1 == -1 && y1 == -1)
		{	// "Pen Up"
			fontColor = COLOR_CLEAR;
			x1 = simplex[charIn - 32][fontIndex++];
			y1 = simplex[charIn - 32][fontIndex++];
			if(x1 == -1 && y1 == -1)
			{
				printf("Two -1 coordinates in a row!\n");
				return(-1);
			}
		}
		if(drawLine(x0 + xpos, y0 + ypos, x1 + xpos, y1 + ypos, fontColor))
		{
			return(-1);
		}
		x0 = x1;
		y0 = y1;
		// "Pen Down" by default
		fontColor = colorFG;
	}
	return(horizSpace);
}
//***********************************************************
//*	Draw a string of characters in the Hershey Vector Font.	*
//***********************************************************
int	drawVectorString(char *theString, int xpos, int ypos, int colorFG)
{
	int	horizSpace;
	while(*theString != '\0')
	{
		horizSpace = drawVectorChar(*theString++, xpos, ypos, colorFG);
		if(horizSpace < 0)
		{
			return(1);
		}
		xpos = xpos + horizSpace;
	}
	return(0);
}

